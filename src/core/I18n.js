export class I18nManager extends EventEmitter {
  constructor(initialLang = APP_CONFIG.defaultLanguage || 'en') {
    super();
    this.currentLanguage = APP_CONFIG.supportedLanguages.includes(initialLang)
      ? initialLang
      : APP_CONFIG.fallbackLanguage;
  }

  setLanguage(lang) {
    if (!APP_CONFIG.supportedLanguages.includes(lang) || lang === this.currentLanguage) return;
    this.currentLanguage = lang;
    this.emit('languageChange', lang);
  }

  getLanguage() {
    return this.currentLanguage;
  }

  /**
   * Resolves a nested key in dot notation (e.g. 'controlPanel.title')
   */
  t(path, fallback = '') {
    const keys = path.split('.');
    let curr = TRANSLATIONS[this.currentLanguage];
    for (const k of keys) {
      if (curr && typeof curr === 'object' && k in curr) {
        curr = curr[k];
      } else {
        // Fallback to English
        let fb = TRANSLATIONS[APP_CONFIG.fallbackLanguage];
        for (const fbk of keys) {
          if (fb && typeof fb === 'object' && fbk in fb) fb = fb[fbk];
          else return fallback || path;
        }
        return fb;
      }
    }
    return curr !== undefined ? curr : (fallback || path);
  }

  getElementName(sym, fallback) {
    const dict = TRANSLATIONS[this.currentLanguage]?.elements;
    return (dict && dict[sym]) || fallback || sym;
  }
}

// Global shared i18n singleton instance
export const i18n = new I18nManager(APP_CONFIG.defaultLanguage || 'en');
